def start_recording(url):
    if not re.match(r"^https?://", url or ""):
        raise ValueError("Paste a full video URL (https://...)")
    probe = subprocess.run(
        [YTDLP, "--no-warnings", "--no-playlist", "--skip-download",
         "--print", "%(id)s\t%(title)s\t%(live_status)s", "--", url],
        capture_output=True, text=True, timeout=90)
    if probe.returncode != 0 or not probe.stdout.strip():
        err = (probe.stderr.strip().splitlines() or ["Couldn't read that URL"])[-1]
        raise ValueError(err.replace("ERROR: ", ""))
    vid, title, live = (probe.stdout.strip().splitlines()[0].split("\t") + ["", ""])[:3]
    if not ID_RE.match(vid):
        raise ValueError("Unexpected video id")
    d = JOBS / vid
    d.mkdir(exist_ok=True)
    meta = read_meta(d) if (d / "meta.json").exists() else {"started": time.time()}
    with lock:
        if recording_alive(vid, meta):
            raise ValueError("Already recording this one")
        meta.update(id=vid, url=url, title=title, live_status=live)
        log = open(d / "record.log", "a")
        p = subprocess.Popen(
            [YTDLP, "--live-from-start", "--no-playlist", "--newline", "-f", "bestaudio",
             "-o", "audio.%(ext)s", "--", url],
            cwd=d, stdout=log, stderr=subprocess.STDOUT, start_new_session=True)
        recorders[vid] = p
        meta["pid"] = p.pid
        write_meta(d, meta)
    return vid


def stop_recording(jid):
    d = job_dir(jid)
    meta = read_meta(d)
    if not recording_alive(jid, meta):
        return
    p = recorders.get(jid)
    if p:
        p.send_signal(signal.SIGINT)
    else:
        os.kill(meta["pid"], signal.SIGINT)


def start_transcription(jid, then_summarize=False):
    d = job_dir(jid)
    final, part = audio_files(d)
    if not (final or part):
        raise ValueError("Nothing recorded yet")
    with lock:
        if jid in transcribing:
            raise ValueError("Already transcribing")
        transcribing.add(jid)

    def run():
        # Only the new audio gets transcribed. The last old line is redone, since it may have
        # been cut off mid-sentence when the previous snapshot was taken.
        old = load_segments(d)
        cut = old[-1]["start"] if old else 0.0
        keep = old[:-1]
        snap = d / "snapshot.wav"
        chunk = d / "chunk.json"
        title = read_meta(d).get("title") or jid
        try:
            live[jid] = (cut, keep)
            # Decode from the cut point into a temp wav; the recorder can keep writing the .part.
            subprocess.run([FFMPEG, "-v", "error", "-y", "-ss", "%.3f" % cut, "-i", str(final or part),
                            "-vn", "-ac", "1", "-ar", "16000", str(snap)], check=True)
            new_len = duration(snap) or 0
            if new_len > 1:
                with open(d / "transcribe.log", "w") as log:
                    code = subprocess.call(
                        [WHISPER, str(snap), "--model", MODEL, "--output-dir", str(d),
                         "--output-name", "chunk", "--output-format", "json"],
                        stdout=log, stderr=subprocess.STDOUT, env={**os.environ, "PYTHONUNBUFFERED": "1"})
                if code != 0:
                    raise RuntimeError((tail(d / "transcribe.log", 1) or ["Transcription failed"])[0])
                new = [{"start": s["start"] + cut, "end": s["end"] + cut, "text": s["text"].strip()}
                       for s in json.loads(chunk.read_text())["segments"] if s["text"].strip()]
                write_transcript(d, keep + new if new else old)
            meta = read_meta(d)
            meta.update(transcribed_seconds=cut + new_len, transcribed_at=time.time(), transcribe_error=None)
            write_meta(d, meta)
            notify("Transcript ready", "%s (%s)" % (title, hms(cut + new_len)), jid)
            if then_summarize:
                with lock:
                    go = jid not in summarizing
                    summarizing.add(jid)
                if go:
                    threading.Thread(target=run_summary, args=(d, True), daemon=True).start()
        except Exception as e:  # surface it in the UI instead of dying silently
            meta = read_meta(d)
            meta["transcribe_error"] = str(e)
            write_meta(d, meta)
            notify("Transcription failed", "%s: %s" % (title, e), jid)
        finally:
            snap.unlink(missing_ok=True)
            chunk.unlink(missing_ok=True)
            live.pop(jid, None)
            transcribing.discard(jid)

    threading.Thread(target=run, daemon=True).start()


def write_summary(d):
    segs = load_segments(d)
    if not segs:
        raise ValueError("Transcribe it first")
    title = read_meta(d).get("title") or d.name
    lines = "\n".join("[%s] %s" % (hms(s["start"]), s["text"]) for s in segs)
    key = os.environ.get("OPENAI_API_KEY") or (KEY_FILE.read_text().strip() if KEY_FILE.exists() else None)
    if not key:
        raise RuntimeError("No OpenAI API key yet. Put it in %s" % KEY_FILE)
    body = {
        "model": SUMMARY_MODEL,
        "instructions": SUMMARY_PROMPT,
        "input": "<transcript title=\"%s\">\n%s\n</transcript>" % (title, lines),
        "max_output_tokens": 32000,
        "text": {"format": {"type": "json_schema", "name": "stream_summary", "strict": True,
                            "schema": SUMMARY_SCHEMA}},
    }
    req = urllib.request.Request("https://api.openai.com/v1/responses", data=json.dumps(body).encode(),
                                 headers={"Authorization": "Bearer " + key, "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=900) as r:
            resp = json.load(r)
    except urllib.error.HTTPError as e:
        try:
            msg = json.load(e)["error"]["message"]
        except Exception:
            msg = e.reason
        if e.code == 401:
            raise RuntimeError("OpenAI key missing or invalid. Put it in %s" % KEY_FILE)
        raise RuntimeError("OpenAI API error %s: %s" % (e.code, msg))
    except OSError as e:
        raise RuntimeError("Couldn't reach the OpenAI API: %s" % e)
    if resp.get("status") != "completed":
        raise RuntimeError("Summary stopped early (%s)" % ((resp.get("incomplete_details") or {}).get("reason")
                                                             or resp.get("status")))
    parts = [c for item in resp.get("output", []) if item.get("type") == "message" for c in item["content"]]
    refusal = next((c["refusal"] for c in parts if c.get("type") == "refusal"), None)
    if refusal:
        raise RuntimeError("The model declined: %s" % refusal)
    data = json.loads("".join(c["text"] for c in parts if c.get("type") == "output_text"))
    usage = resp.get("usage") or {}
    for p in data["key_points"]:
        try:
            p["s"] = seconds(p["timestamp"].strip("[]"))
        except ValueError:
            p["s"] = None
    data.update(covers_seconds=segs[-1]["end"], created_at=time.time(), model=resp.get("model"),
                input_tokens=usage.get("input_tokens"), output_tokens=usage.get("output_tokens"))
    (d / "transcript" / "summary.json").write_text(json.dumps(data, indent=2))
    return data


def start_summary(jid):
    d = job_dir(jid)
    if not load_segments(d):
        raise ValueError("Transcribe it first")
    with lock:
        if jid in summarizing:
            raise ValueError("Already summarizing")
        summarizing.add(jid)
    threading.Thread(target=run_summary, args=(d,), daemon=True).start()


def run_summary(d, save=False):
    """Blocking; the caller has already added d.name to summarizing."""
    title = read_meta(d).get("title") or d.name
    try:
        data = write_summary(d)
        meta = read_meta(d)
        meta["summary_error"] = None
        write_meta(d, meta)
        notify("Summary ready", "%s\n\n%s" % (title, data["tldr"]), d.name)
        if save:
            try:
                save_to_vault(d.name)
            except Exception as e:
                print("vault save skipped:", e)
    except Exception as e:
        meta = read_meta(d)
        meta["summary_error"] = str(e)
        write_meta(d, meta)
        notify("Summary failed", "%s: %s" % (title, e), d.name)
    finally:
        summarizing.discard(d.name)


def stream_is_live(url):
    probe = subprocess.run([YTDLP, "--no-warnings", "--no-playlist", "--skip-download",
                            "--print", "%(live_status)s", "--", url], capture_output=True, text=True, timeout=90)
    return probe.stdout.strip() in ("is_live", "is_upcoming")


def finalize(d):
    """Turn a leftover .part into a normal audio file. Only once the stream is over: Resume needs the .part."""
    final, part = audio_files(d)
    if final or not part:
        return
    out = d / part.stem  # audio.m4a.part -> audio.m4a
    tmp = d / ("finalizing" + out.suffix)
    subprocess.run([FFMPEG, "-v", "error", "-y", "-i", str(part), "-vn", "-c", "copy", str(tmp)], check=True)
    tmp.rename(out)
    part.unlink()
    (d / (part.stem + ".ytdl")).unlink(missing_ok=True)


def delete_job(jid):
    d = job_dir(jid)
    if recording_alive(jid, read_meta(d)) or jid in transcribing or jid in summarizing:
        raise ValueError("Stop the recording and wait for transcripts and summaries to finish first")
    shutil.rmtree(d)


def title_of(meta, jid):
    """yt-dlp appends the date and time to live-stream titles; drop it."""
    return re.sub(r"\s\d{4}-\d{2}-\d{2} \d{2}:\d{2}$", "", meta.get("title") or jid)


